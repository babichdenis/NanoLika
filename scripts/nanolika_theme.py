def replace_values(path: Path, values: dict[str, str]) -> None:
    """Change named Kotlin colour constants, without changing identifiers."""
    text = path.read_text()
    for name, color in values.items():
        text = re.sub(rf"({name} = )Color\([^)]*\)", rf"\g<1>Color(0xFF{color})", text)
    marker = "// NanoLika: generated paper/sage values from scripts/nanolika_theme.py.\n"
    if marker not in text:
        at = text.index("private val " if "private val Teal" in text else "val LightChatPalette")
        text = text[:at] + marker + text[at:]
    path.write_text(text)


def swift_color(light: str, dark: str) -> str:
    """A dynamic UIKit colour, resolved by the person's appearance choice."""
    def rgb(color: str) -> str:
        channels = [int(color[i:i + 2], 16) / 255 for i in [0, 2, 4]]
        return "UIColor(red: %.5f, green: %.5f, blue: %.5f, alpha: 1)" % tuple(channels)
    return f"Color(UIColor {{ $0.userInterfaceStyle == .dark ? {rgb(dark)} : {rgb(light)} }})"


