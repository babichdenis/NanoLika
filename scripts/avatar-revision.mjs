/** Content keys for bundled faces. Run before client builds, including same-version rebuilds. */
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

export function avatarRevision(folder) {
  const hash = createHash('sha256')
  for (const mood of ['idle', 'working', 'waiting', 'happy', 'error']) {
    for (const ext of mood === 'error' ? ['webp'] : ['webp', 'mp4']) {
      const name = `dragon-${mood}.${ext}`
      hash.update(name)
      hash.update(readFileSync(new URL(name, folder)))
    }
  }
  return hash.digest('hex').slice(0, 16)
}

export function generateAvatarRevisions() {
  for (const [folder, target] of [
    ['../web/public/avatars/', '../web/src/avatar-revision.ts'],
    ['../harness/dsh-nanomuse/assets/', '../harness/dsh-nanomuse/src/client/avatar-revision.ts'],
  ]) {
    const revision = avatarRevision(new URL(folder, import.meta.url))
    const source = `// Generated by scripts/avatar-revision.mjs from the packaged artwork.\nexport const BUILTIN_AVATAR_REVISION = "${revision}";\n`
    const path = new URL(target, import.meta.url)
    let old = ''
    try { old = readFileSync(path, 'utf8') } catch { /* first build */ }
    if (source !== old) writeFileSync(path, source)
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) generateAvatarRevisions()
